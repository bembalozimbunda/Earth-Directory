export function getCentralBankByIso(iso: string): CentralBankProfile | undefined {
  if (!iso) return undefined;
  return CENTRAL_BANK_REGISTRY.find(b => b.isoCode.toUpperCase() === iso.toUpperCase());
}

export function getCentralBankByNation(nation: string): CentralBankProfile | undefined {
  if (!nation) return undefined;
  const q = nation.toLowerCase().trim();
  return CENTRAL_BANK_REGISTRY.find(b => 
    b.nationName.toLowerCase() === q ||
    b.nationName.toLowerCase().includes(q) ||
    q.includes(b.nationName.toLowerCase())
  );
}
